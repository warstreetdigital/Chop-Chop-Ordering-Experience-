export const menu = {
  categories: MENU_CATEGORIES,
  items: MENU_ITEMS,
  // Helper filter by category
  getItemsByCategory: (categoryId) => {
    if (!categoryId || categoryId === 'all') return MENU_ITEMS;
    return MENU_ITEMS.filter(it => it.category === categoryId || (it.categories && it.categories.includes(categoryId)));
  },
  getItemById: (itemId) => {
    return MENU_ITEMS.find(it => it.id === itemId);
  },
};

export default menu;
